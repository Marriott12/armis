function armisCredentialStoreDir(): string
{
    $dir = dirname(__DIR__) . '/cache/generated_credentials';
    if (!is_dir($dir)) {
        @mkdir($dir, 0700, true);
    }
    return $dir;
}

function armisStoreGeneratedCredentials(array $credentials): ?string
{
    if (!$credentials) {
        return null;
    }
    $token = bin2hex(random_bytes(32));
    $path = armisCredentialStoreDir() . '/' . $token . '.json';
    $payload = json_encode([
        'created_at' => time(),
        'expires_at' => time() + 3600,
        'credentials' => array_values($credentials),
    ], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    if ($payload === false || @file_put_contents($path, $payload, LOCK_EX) === false) {
        return null;
    }
    @chmod($path, 0600);
    return $token;
}

function armisLoadGeneratedCredentials(): array
{
    $token = $_SESSION['armis_generated_credentials_token'] ?? '';
    if ($token === '' || !preg_match('/^[a-f0-9]{64}$/', $token)) {
        // Backward compatibility with credentials generated by the previous session-based version.
        return is_array($_SESSION['armis_generated_credentials'] ?? null) ? $_SESSION['armis_generated_credentials'] : [];
    }
    $path = armisCredentialStoreDir() . '/' . $token . '.json';
    if (!is_file($path)) {
        unset($_SESSION['armis_generated_credentials_token']);
        return [];
    }
    $raw = @file_get_contents($path);
    $data = is_string($raw) ? json_decode($raw, true) : null;
    if (!is_array($data) || !isset($data['expires_at'], $data['credentials']) || (int)$data['expires_at'] < time()) {
        @unlink($path);
        unset($_SESSION['armis_generated_credentials_token']);
        return [];
    }
    return is_array($data['credentials']) ? $data['credentials'] : [];
}

function armisClearGeneratedCredentials(): void
{
    $token = $_SESSION['armis_generated_credentials_token'] ?? '';
    if (is_string($token) && preg_match('/^[a-f0-9]{64}$/', $token)) {
        @unlink(armisCredentialStoreDir() . '/' . $token . '.json');
    }
    unset($_SESSION['armis_generated_credentials_token'], $_SESSION['armis_generated_credentials']);
}

function armisGenerateStaffTempPassword(): string
{
    $upper = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
    $lower = 'abcdefghijkmnopqrstuvwxyz';
    $digits = '23456789';
    $special = '@#$%';
    $pool = $upper . $lower . $digits . $special;
    $password = $upper[random_int(0, strlen($upper) - 1)]
        . $lower[random_int(0, strlen($lower) - 1)]
        . $digits[random_int(0, strlen($digits) - 1)]
        . $special[random_int(0, strlen($special) - 1)];
    for ($i = 4; $i < 12; $i++) {
        $password .= $pool[random_int(0, strlen($pool) - 1)];
    }
    $chars = str_split($password);
    for ($i = count($chars) - 1; $i > 0; $i--) {
        $j = random_int(0, $i);
        [$chars[$i], $chars[$j]] = [$chars[$j], $chars[$i]];
    }
    return implode('', $chars);
}

/**
 * Create a login directly on the canonical ARMIS staff table.
 * This function intentionally does not reference or depend on a users table.
 */
function armisCreateStaffAccount(PDO $pdo, string $svcNo, string $firstName, string $lastName, string $email = ''): array
{
    $svcNo = trim($svcNo);
    if ($svcNo === '') {
        return ['success' => false, 'message' => 'Service number is empty.'];
    }

    try {
        $check = $pdo->prepare('SELECT svcNo, username, password FROM staff WHERE svcNo = ? LIMIT 1');
        $check->execute([$svcNo]);
        $staff = $check->fetch(PDO::FETCH_ASSOC);
        if (!$staff) {
            return ['success' => false, 'message' => 'Staff record not found in staff table.'];
        }

        if (trim((string)($staff['username'] ?? '')) !== '' || trim((string)($staff['password'] ?? '')) !== '') {
            return ['success' => false, 'message' => 'This staff member already has an account.'];
        }

        // The service number is the canonical and deterministic username.
        // It is also accepted by authenticateUser() as a login identifier.
        $username = substr(preg_replace('/[^A-Za-z0-9._-]/', '', $svcNo), 0, 25);
        if ($username === '') {
            return ['success' => false, 'message' => 'Unable to derive a valid username from the service number.'];
        }

        $unique = $pdo->prepare('SELECT svcNo FROM staff WHERE username = ? AND svcNo <> ? LIMIT 1');
        $unique->execute([$username, $svcNo]);
        if ($unique->fetchColumn()) {
            return ['success' => false, 'message' => 'The service number is already assigned as a username to another staff record.'];
        }

        // Use the existing secure generator only for the temporary password;
        // the actual account write below is explicitly against staff.
        $tempPassword = armisGenerateStaffTempPassword();
        $hash = password_hash($tempPassword, PASSWORD_DEFAULT);
        if ($hash === false) {
            return ['success' => false, 'message' => 'Unable to hash the temporary password.'];
        }

        $sql = "UPDATE staff
                   SET username = ?, password = ?, accStatus = 'Active',
                       isFirstLogin = 1, passwordChangedAt = NULL
                 WHERE svcNo = ?
                   AND (username IS NULL OR username = '')
                   AND (password IS NULL OR password = '')";
        $update = $pdo->prepare($sql);
        $update->execute([$username, $hash, $svcNo]);

        if ($update->rowCount() !== 1) {
            $verify = $pdo->prepare('SELECT username, password FROM staff WHERE svcNo = ? LIMIT 1');
            $verify->execute([$svcNo]);
            $after = $verify->fetch(PDO::FETCH_ASSOC);
            if ($after && (!empty($after['username']) || !empty($after['password']))) {
                return ['success' => false, 'message' => 'Account was created concurrently or credentials now exist for this staff record.'];
            }
            return ['success' => false, 'message' => 'UPDATE staff affected 0 rows. No users table is involved. Verify the live staff record and database permissions.'];
        }

        return [
            'success' => true,
            'svcNo' => $svcNo,
            'username' => $username,
            'password' => $tempPassword,
            'message' => 'Account created directly in staff.username and staff.password.'
        ];
    } catch (PDOException $e) {
        $info = $e->errorInfo ?? [];
        $state = $info[0] ?? $e->getCode();
        $driver = $info[1] ?? '';
        $detail = $info[2] ?? $e->getMessage();
        error_log("ARMIS staff account creation failed for {$svcNo}: SQLSTATE={$state} DRIVER={$driver} {$detail}");
        return ['success' => false, 'message' => "Database error [{$state}/{$driver}]: {$detail}"];
    }
}

