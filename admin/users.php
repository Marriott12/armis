function confirmBulkCreate() {
    const missing = <?= (int)($userStats['active_without_accounts'] ?? 0) ?>;
    return confirm('Create login accounts for ' + missing + ' active personnel who do not currently have complete credentials? Existing accounts will NOT be overwritten. Temporary passwords will be generated and shown once on this page.');
}
function resetPassword(svcNo, forced) {
    document.getElementById('reset_svcNo').value = svcNo;
    document.getElementById('resetSvcDisplay').textContent = svcNo;
    const btn = document.getElementById('confirmResetBtn');
    btn.innerHTML = '<i class="fas fa-key me-1"></i> ' + (forced ? 'Force Reset Password' : 'Generate Temporary Password');
    const modalEl = document.getElementById('resetPasswordModal');
    if (window.bootstrap && bootstrap.Modal) bootstrap.Modal.getOrCreateInstance(modalEl).show();
    else if (confirm('Reset the password for ' + svcNo + '?')) document.getElementById('resetPasswordForm').submit();
}
function copyResetCredential(value, button) {
    navigator.clipboard.writeText(value).then(function() {
        const original = button.innerHTML;
        button.innerHTML = '<i class="fas fa-check me-1"></i> Copied';
        setTimeout(() => button.innerHTML = original, 1800);
    });
}

(function initDynamicUserSearch() {
    const input = document.getElementById('userSearch');
    const clear = document.getElementById('clearUserSearch');
    const count = document.getElementById('userSearchCount');
    if (!input) return;
    const rows = Array.from(document.querySelectorAll('#usersTable tbody tr.user-row'));
    function applyFilter() {
        const query = input.value.trim().toLowerCase();
        let visible = 0;
        rows.forEach(row => {
            const match = !query || (row.dataset.search || '').includes(query);
            row.style.display = match ? '' : 'none';
            if (match) visible++;
        });
        if (count) count.textContent = visible + ' of ' + rows.length + ' accounts shown';
    }
    input.addEventListener('input', applyFilter);
    clear.addEventListener('click', function() { input.value = ''; input.focus(); applyFilter(); });
    applyFilter();
})();
</script>

